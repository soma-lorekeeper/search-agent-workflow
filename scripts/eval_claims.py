def route(claim: dict) -> list[tuple[str, dict]]:
    """claim_type이 채널을 결정한다 — LLM에게 도구를 고르게 하지 않는다.

    평가에서 도구 선택을 모델에 맡기면 매 실행마다 선택이 흔들려, 프롬프트 수정의 효과와
    선택의 요동을 구분할 수 없다. 라우팅을 코드로 고정하면 "이 타입엔 이 채널"이라는
    가설 자체가 측정 대상이 된다.
    """
    subject = (claim.get("subject") or "").strip()
    attribute = (claim.get("attribute") or "").strip()
    value = str(claim.get("value") or "").strip()
    ctype = claim.get("claim_type")
    calls: list[tuple[str, dict]] = []

    if ctype == "행위귀속":
        # 주어를 빼고 행위로만 묻는다. 초고가 지목한 주어는 틀린 값일 수 있고, 틀린 이름으로
        # 검색하면 반박 근거(진짜 주체가 참가자로 달린 사실)에 영원히 못 닿는다.
        calls.append(("fact_search", {"query_text": attribute or claim.get("quote", "")}))
    elif ctype == "규칙제약":
        calls.append(("hybrid_search", {"query_text": f"{attribute} {value}".strip()}))
        calls.append(("fact_search", {"query_text": attribute or value}))
    elif ctype == "상태존재":
        if subject:
            calls.append(("entity_search", {"entity_name": subject}))
        calls.append(("fact_search", {"query_text": f"{subject} {attribute}".strip()}))
    else:  # 속성값(기본)
        if subject:
            calls.append(("entity_search", {"entity_name": subject}))
        # value(초고가 주장하는 값)까지 넣는다. 값이 틀렸다면 그 값은 다른 대상에게
        # 붙어 있고(예: 별칭 '강철검제'는 이현성의 것), 맞다면 같은 대상에게 붙어 있다 —
        # 어느 쪽이든 반박/지지 근거가 있는 자리를 가리키는 앵커가 된다.
        calls.append(
            ("hybrid_search", {"query_text": f"{subject} {attribute} {value}".strip()})
        )
    return calls


def route_broadcast(claim: dict, slim: bool = False) -> list[tuple[str, dict]]:
    """브로드캐스트 라우팅 — claim_type 분기 없이 전 claim에 같은 채널 세트를 연다.

    마커(도달 판정 기준)는 과거 회차 원문 문장이므로 원문 청크를 직접 때리는 hybrid를
    전 claim에 열고, 원문 어휘(quote)와 정규화 서술 두 계열을 다 보낸다. 어느 문체가
    임베딩에 걸릴지는 케이스마다 반대라서(sav 실측에서 v5-GT2는 추상 표현이, v4-GT1은
    원문 표현이 도달했다) 둘 다 보내는 것이 헤지다. 채널이 늘어난 만큼 stage_retrieve의
    item 단위 dedupe가 세트다.

    두 스키마를 모두 받는다 — stm은 statement/entity를, sav는 subject+attribute+value
    조합을 "정규화 서술" 자리에 넣는다(스키마를 고정한 채 라우팅만 비교하기 위해서다).
    """
    quote = (claim.get("quote") or "").strip()
    if claim.get("statement") is not None:  # stm 스키마
        normalized = (claim.get("statement") or "").strip()
        anchor = (claim.get("entity") or "").strip()
    else:  # sav 스키마 — statement 자리를 세 필드 결합으로 대신한다
        anchor = (claim.get("subject") or "").strip()
        attribute = (claim.get("attribute") or "").strip()
        value = str(claim.get("value") or "").strip()
        normalized = f"{anchor} {attribute} {value}".strip()

    calls: list[tuple[str, dict]] = []
    if anchor:
        calls.append(("entity_search", {"entity_name": anchor}))
    calls.append(("hybrid_search", {"query_text": quote}))
    calls.append(("fact_search", {"query_text": quote}))
    if normalized and norm(normalized) != norm(quote):  # 동일 문구면 임베딩 호출만 낭비
        calls.append(("hybrid_search", {"query_text": normalized}))
        # slim은 fact(normalized)를 뺀다 — 채널 ablation에서 마커 기여 7건이 전부 다른
        # 채널과 겹쳤고 단독 기여가 0건이라, 빼도 도달률은 그대로면서 토큰만 16% 준다.
        if not slim:
            calls.append(("fact_search", {"query_text": normalized}))
    return calls


def route_qav(claim: dict, with_quote: bool = False) -> list[tuple[str, dict]]:
    """qav 라우팅 — `axis`와 `axis: value` 두 계열을 hybrid·fact 두 채널에 보낸다.

    entity_search를 열지 않는다. 이름 조회는 인물의 사실 이력을 LIMIT 60까지 통째로 긁어와
    fact_search 결과와 대부분 겹쳤고, 겹치지 않는 꼬리는 청크 29개·사실 18개뿐이었다.
    그 대신 사실에 붙은 소속·소유·무대는 fact_search의 `[연관]` 줄이 직접 실어 온다.

    quote 계열을 기본에서 뺀 것은 실측 결과다 — quote×2+`axis:값`×2와 axis×2+`axis:값`×2가
    도달 23/24로 동률이었고 문서고 고유 노드도 274 vs 272로 같았다. 다만 그 측정은 axis를
    사람이 고른 것이라 "추출기가 axis를 빗맞혔을 때"의 위험이 0이었다. with_quote는 그
    안전망을 A/B로 재기 위한 스위치다(--route qav-q).

    두 계열이 상보적인 이유: axis는 오류 토큰이 없어 값이 틀린 claim에서도 대조축을 정확히
    가리키고(v5-GT5의 '칸 사이 이동 가능 여부'가 이 계열로만 도달했다), `axis: value`는
    값 어휘 자체가 단서인 claim을 잡는다(v1-GT3의 '죽음').
    """
    axis = (claim.get("axis") or "").strip()
    value = str(claim.get("value") or "").strip()
    quote = (claim.get("quote") or "").strip()

    calls: list[tuple[str, dict]] = []
    if with_quote and quote:
        calls.append(("hybrid_search", {"query_text": quote}))
        calls.append(("fact_search", {"query_text": quote}))
    if axis:
        calls.append(("hybrid_search", {"query_text": axis}))
        calls.append(("fact_search", {"query_text": axis}))
        if value:
            av = f"{axis}: {value}"
            calls.append(("hybrid_search", {"query_text": av}))
            calls.append(("fact_search", {"query_text": av}))
    elif quote and not with_quote:  # axis가 비면 quote라도 던져야 근거가 0이 되지 않는다
        calls.append(("hybrid_search", {"query_text": quote}))
        calls.append(("fact_search", {"query_text": quote}))
    return calls


def stage_retrieve(
    run_tag: str,
    draft: str,
    top_k: int,
    route_mode: str | None = None,
    include_graph: bool = False,
    workers: int = 8,
) -> dict:
    """claim마다 라우팅이 정한 채널을 열어 근거를 모은다.

    claim 단위로 병렬 실행한다. 호출 하나가 임베딩 API 1회 + Neo4j 질의 1회라 전부 네트워크
    대기이고(순차 실행 시 CPU는 놀면서 호출당 0.5초씩 벽시계만 갔다), claim 사이에는 의존이
    전혀 없다 — dedupe에 쓰는 `seen`도 claim 안에서만 산다. 결과 순서는 claims 순서를 그대로
    유지해야 한다(문서고의 claim_index가 이 순서를 키로 쓴다).
    """
    claims_payload = json.loads(
        (OUT_DIR / f"claims_{run_tag}_{draft}.json").read_text(encoding="utf-8")
    )
    schema = claims_payload.get("schema", "sav")
    mode = route_mode or DEFAULT_ROUTE[schema]
    if mode == "type":
        route_fn = route
    elif mode in ("qav", "qav-q"):
        route_fn = lambda c: route_qav(c, with_quote=(mode == "qav-q"))  # noqa: E731
    else:
        route_fn = lambda c: route_broadcast(c, slim=(mode == "slim"))  # noqa: E731
    # 부록([관련 그래프])은 기본으로 안 온다 — 예전엔 받아서 텍스트에서 떼어냈지만(trim_graph)
    # 이제 retriever가 애초에 수집하지 않아 쿼리 자체가 가벼워진다. 등가성은 항목 단위로
    # 검증했다(trim(ON) == OFF, 179/179).
    _, tools_by_name = build_openai_tools(include_graph)

    def retrieve_one(claim: dict) -> tuple[dict, int]:
        """claim 하나의 전 채널. 스레드에서 돌므로 바깥 상태를 건드리지 않는다."""
        channels: list[dict] = []
        n_dropped = 0
        # 브로드캐스트는 채널 5개가 같은 청크를 반복해 물어오므로 claim 단위로 dedupe한다.
        # item.content를 무가공 그대로 싣거나 통째로 스킵만 한다 — 텍스트를 가공하면
        # 마커 부분일치 규약이 깨진다. 판정은 채널 합집합으로 하므로 도달률에 영향 없다.
        seen: set[str] = set()
        for tool_name, args in route_fn(claim):
            if tool_name != "entity_search":
                args = {**args, "top_k": top_k}
            items: list[dict] = []
            try:
                result = tools_by_name[tool_name].execute(**args)
                # items는 dedupe 이전의 전체 결과를 담는다 — dedupe는 "이 claim의 앞 채널과
                # 겹친다"는 이유로 버리는 건데, claim이 그 노드를 참조했다는 사실 자체는
                # 남아야 문서고가 claim↔노드 연결을 복원할 수 있다. 조립기가 eid로 다시
                # 병합하므로 중복은 무해하다. content는 파일 크기 때문에 싣지 않는다
                # (채널 content에 이미 있고, metadata의 text/evidence[].text로 복원된다).
                items = [{"metadata": item.metadata or {}} for item in result.items]
                if mode != "type" and result.items:
                    kept = []
                    for item in result.items:
                        key = norm(item.content)
                        if key in seen:
                            n_dropped += 1
                            continue
                        seen.add(key)
                        kept.append(item.content)
                    content = "\n\n".join(
                        f"[결과 {i}]\n{c}" for i, c in enumerate(kept, 1)
                    ) or "(모든 결과가 이 claim의 앞 채널과 중복이라 생략)"
                else:
                    content = format_tool_result(result)
            except Exception as exc:  # noqa: BLE001 — 실패도 "근거 없음"으로 기록하고 계속
                content = f"(도구 실행 오류: {exc})"
            channels.append(
                {"tool": tool_name, "args": args, "content": content, "items": items}
            )
        return {"claim": claim, "channels": channels}, n_dropped

    claims = claims_payload["claims"]
    # executor.map은 입력 순서대로 결과를 돌려준다 — claim_index가 이 순서에 묶여 있어
    # as_completed로 바꾸면 문서고의 claim↔노드 대응이 어긋난다.
    with ThreadPoolExecutor(max_workers=workers) as pool:
        results = list(pool.map(retrieve_one, claims))
    records = [r for r, _ in results]
    dropped = sum(n for _, n in results)  # dedupe로 걸러진 결과 항목 수(로그용)

    payload = {
        "run": run_tag, "draft": draft, "top_k": top_k, "schema": schema,
        "route": mode, "include_graph": include_graph, "records": records,
    }
    out = OUT_DIR / f"evidence_{run_tag}_{draft}.json"
    out.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    calls = sum(len(r["channels"]) for r in records)
    dedup_note = f" (dedupe로 결과 항목 {dropped}개 생략)" if mode != "type" else ""
    print(f"  [retrieve] {draft}: claim {len(records)}개 → 검색 {calls}회{dedup_note}")
    return payload


