def build_system_prompt(draft_text: str | None, scope: str, schema: str = "sav") -> str:
    """추출용 system 프롬프트.

    정적 부분(기준 + few-shot)을 앞에, 초고마다 바뀌는 전문을 뒤에 둔다 — 프롬프트 캐시는
    prefix 일치로 동작하므로 이 순서라야 초고를 바꿔가며 돌릴 때도 앞부분 캐시가 산다.
    """
    static = {
        "sav": [_CRITERIA, _FEWSHOT],
        "lean": [_CRITERIA_LEAN, _FEWSHOT_LEAN],
        "stm": [_CRITERIA_STM, _FEWSHOT_STM],
        "qav": [_CRITERIA_QAV, _FEWSHOT_QAV],
        "qav2": [_CRITERIA_QAV2, _FEWSHOT_QAV2],
        "qav3": [_CRITERIA_QAV3, _FEWSHOT_QAV3],
        "qav4": [_CRITERIA_QAV4, _FEWSHOT_QAV4],
    }[schema]
    parts = static + [scope]
    # 노드 목록은 초고가 바뀌어도 그대로라 원고 앞에 둔다 — 프롬프트 캐시의 안정 prefix가 된다.
    if schema in ("qav", "qav2", "qav3", "qav4"):
        parts.append(_NODE_HEADER + "\n" + entity_node_text())
    if draft_text is not None:
        parts.append(f"[신규 회차 원고 전체]\n{draft_text}")
    return "\n\n".join(parts)


def cap_for(length: int) -> int:
    """폭주 방지 상한. 입력 길이에 비례시킨다(30자당 1개).

    이 값은 두 번 고쳤다. 처음엔 청크당 10개 고정이었는데 인물 정보 카드처럼 사실이
    밀집한 구간에서 즉시 소진돼 뒤쪽 서술이 통째로 잘렸고(v1에서 GT 3건 손실), 100자당
    1개로 바꾼 뒤에도 실제 추출량이 상한의 82~108%에 붙어 있었다 — 여전히 상한이 결과를
    결정하고 있었다는 뜻이다. 특히 청크를 쪼개면 청크당 상한이 같은 비율로 줄어 총량이
    더 깎이므로, 상한이 포화된 상태에서는 chunk-size 비교 자체가 성립하지 않는다.
    지금 값은 어떤 구성에서도 상한이 바인딩되지 않게 넉넉히 잡은 것이다.
    """
    return max(20, length // 30)


