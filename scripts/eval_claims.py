# 등장인물 노드 — qav 추출에만 붙는다(sav baseline은 재현성 때문에 그대로 둔다).
#
# 왜 필요한가: 원고가 1인칭이라 주인공 이름이 **5편 전부에서 0회** 등장한다. "그 여자도 나와
# 같은 계약직이었다"에는 유상아라는 단서가 원고 안에 없다. 그래서 추출기가 axis를 `화자의
# 나이`·`주인공의 소지품`으로 쓰고, 그런 질의는 검색 앵커로 작동하지 않는다(claim의 22%가
# 이 상태였다). sav가 `subject="김독자"`를 채울 수 있었던 건 모델이 이 유명 작품을 알아서지
# 원고에서 읽어낸 게 아니다 — 신인 작가 원고에서는 재현되지 않는 이점이라 기대면 안 된다.
#
# 왜 CharacterState만인가: 상태는 원고 표면에 신호가 없다("그가 왼팔을 들었다"는 과거에 그
# 팔을 잃었다는 걸 알아야만 의심 대상이 된다). 반대로 Event는 표면에 신호가 있어("~했던",
# "처음 ~한") 이 목록 없이도 추출된다 — 실제로 과거 사건을 다투는 GT는 전부 추출되고 있다.
# 그리고 확장성이 정반대다: 상태는 인물당 속성이라 갱신되며 완만히 늘지만, 사건은 회차마다
# 순수 누적이라 100화면 800개가 된다. **회차 수에 비례해 자라는 정보는 추출에 넣지 않는다** —
# 그건 검색이 할 일이고, 넣기 시작하면 RAG를 만든 이유 자체가 무너진다.
_ENTITY_NODE_QUERY = """
MATCH (c:Character)
OPTIONAL MATCH (c)-[:HAS_STATE]->(s:CharacterState)
OPTIONAL MATCH (s)-[:ABOUT]->(t)
WITH c, s, t ORDER BY s.name
RETURN c.name AS name, c.aliases AS aliases,
       [x IN collect(DISTINCT {st: s.name, tgt: t.name}) WHERE x.st IS NOT NULL] AS states
ORDER BY c.name
"""

_entity_node_cache: str | None = None


def entity_node_text() -> str:
    """과거 회차에서 확립된 인물과 그 상태를 노드 목록으로 렌더한다(프로세스당 1회 조회).

    실전에서는 "이번 회차 직전까지"로 잘라야 하지만, 평가셋은 KG가 1~5화이고 초고가 6화라
    전체가 곧 과거다. 회차 컷이 필요해지면 CharacterState의 ESTABLISHED_IN을 타면 된다.
    """
    global _entity_node_cache
    if _entity_node_cache is not None:
        return _entity_node_cache

    from lorekeeper.client import get_driver

    driver = get_driver()
    with driver.session() as session:
        rows = [dict(r) for r in session.run(_ENTITY_NODE_QUERY)]

    lines: list[str] = []
    for r in rows:
        head = r["name"]
        if r["aliases"]:
            head += f" [별칭: {r['aliases']}]"
        lines.append(head)
        for s in r["states"]:
            tgt = f" → {s['tgt']}" if s.get("tgt") else ""
            lines.append(f"  - {s['st']}{tgt}")
    _entity_node_cache = "\n".join(lines)
    return _entity_node_cache


