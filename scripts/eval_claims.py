def _cache_path(
    model: str, effort: str | None, system: str, user: str, sample: int = 0
) -> Path:
    # sample>0일 때만 키에 섞는다 — 0은 예전 키 그대로라 기존 캐시가 그대로 재사용된다.
    # 요청 본문은 회차와 무관하게 동일하다. 즉 회차는 "캐시 칸을 나눌 뿐"이고, 그래서
    # 같은 조건에서 독립적으로 다시 샘플링한 결과를 얻는다(이 모델은 seed가 듣지 않는다).
    parts = [model, effort or "-", system, user]
    if sample:
        parts.append(f"sample{sample}")
    key = hashlib.sha1("|".join(parts).encode("utf-8")).hexdigest()
    return CACHE_DIR / f"{key}.json"


async def _extract_one(
    system: str, user: str, effort: str | None, sample: int = 0
) -> tuple[list[dict], dict]:
    """LLM 호출 1회. 캐시가 있으면 그것을 쓴다."""
    cached_at = _cache_path(EXTRACT_MODEL, effort, system, user, sample)
    if cached_at.exists():
        payload = json.loads(cached_at.read_text(encoding="utf-8"))
        return payload["claims"], payload["usage"]

    kwargs = {
        "model": EXTRACT_MODEL,
        "response_format": {"type": "json_object"},
        "prompt_cache_key": EXTRACT_CACHE_KEY,
        "messages": [
            {"role": "system", "content": system},
            {"role": "user", "content": user},
        ],
    }
    # 지정하지 않으면 파라미터 자체를 빼서 API 기본값을 쓴다(pipeline.py:102-105와 같은 방식).
    if effort:
        kwargs["reasoning_effort"] = effort

    response = await _client.chat.completions.create(**kwargs)
    data = json.loads(response.choices[0].message.content or "{}")
    claims = data.get("claims", []) or []
    used = usage.from_response(response)

    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    cached_at.write_text(
        json.dumps({"claims": claims, "usage": used}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    return claims, used


async def stage_extract(
    variant: str,
    draft: str,
    effort: str | None,
    schema: str = "sav",
    route_mode: str | None = None,
    include_graph: bool = False,
    sample: int = 0,
) -> dict:
    chunk_size, include_draft = VARIANTS[variant]
    text = (DATA_DIR / f"{DRAFTS[draft]}.txt").read_text(encoding="utf-8")

    if chunk_size is None:
        scope = _SCOPE_WHOLE.replace("{max_claims}", str(cap_for(len(text))))
        # qav2는 원고를 `L1: …` 형태로 준다. whole variant는 include_draft=False라 system에는
        # 원고가 없으므로 user 메시지만 바꾸면 되고, 캐시 키가 (system, user) 해시라 자동으로
        # 갈린다.
        units = [number_lines(split_lines(text))] if schema in ("qav2", "qav3", "qav4") else [text]
    else:
        # 상한은 실제 청크 길이가 아니라 설정된 청크 크기로 계산한다 — 청크마다 값이
        # 달라지면 system 프롬프트가 달라져 프롬프트 캐시가 깨진다.
        template = _SCOPE_CHUNK if include_draft else _SCOPE_CHUNK_NO_DRAFT
        scope = template.replace("{max_claims}", str(cap_for(chunk_size)))
        if schema in ("qav2", "qav3", "qav4"):
            # 번호는 **초고 전역으로 한 번** 매긴 뒤 그 라인들을 조각으로 묶는다. 조각마다
            # 다시 1부터 매기면 L번호가 초고 안에서 유일하지 않게 되어 라인 위생 측정과
            # 판정의 근거 지시가 둘 다 깨진다. 경계도 라인에서만 끊어 문장이 잘리지 않는다.
            units, cur, size = [], [], 0
            for line in number_lines(split_lines(text)).split("\n"):
                if cur and size + len(line) > chunk_size:
                    units.append("\n".join(cur))
                    cur, size = [], 0
                cur.append(line)
                size += len(line)
            if cur:
                units.append("\n".join(cur))
        else:
            raw = await KSSSentenceSplitter(chunk_size=chunk_size, chunk_overlap=0).run(text)
            units = [c.text for c in raw.chunks]

    system = build_system_prompt(text if include_draft else None, scope, schema)
    results = await asyncio.gather(
        *[_extract_one(system, u, effort, sample) for u in units]
    )

    claims = [c for cs, _ in results for c in cs]
    # 조각을 다 합친 **뒤에** 번호를 매긴다 — 조각별로 매기면 경계에서 충돌한다.
    assign_claim_ids(claims)
    payload = {
        "variant": variant,
        "draft": draft,
        "model": EXTRACT_MODEL,
        "effort": effort or "(미지정)",
        "schema": schema,
        "chunks": len(units),
        "claims": claims,
        "usage": usage.merge([u for _, u in results]),
    }
    out = (
        OUT_DIR
        / f"claims_{tag(variant, effort, schema, route_mode, include_graph, sample)}_{draft}.json"
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(
        f"  [extract] {draft}: 청크 {len(units)}개 → claim {len(claims)}개 "
        f"(prompt {payload['usage']['prompt_tokens']:,} / "
        f"cached {payload['usage']['cached_tokens']:,} / "
        f"completion {payload['usage']['completion_tokens']:,})"
    )
    return payload


