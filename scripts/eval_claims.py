def match_claim_indices(gt_quote: str, claims: list[dict], norm_draft: str) -> list[int]:
    """GT에 매칭되는 claim의 인덱스 목록. stage_score의 quote-키 방식과 달리 인덱스를 쓴다.

    같은 quote를 공유하는 claim이 실제로 있어서(v2의 "스물다섯의 계약직으로 살아온 내가"가
    나이·직업 두 claim으로 뽑힘) quote를 키로 쓰면 둘이 뭉개진다. 매칭 규약(match_kind)은
    그대로 재사용한다.
    """
    return [i for i, c in enumerate(claims) if match_kind(gt_quote, c, norm_draft)]


def marker_bearing_aliases(store: dict, markers: list[str]) -> set[str]:
    """마커 문장을 실제로 담고 있는 문서고 노드의 별칭. 접지 재현율의 정답지다."""
    out = set()
    for c in store["chunks"].values():
        if any(norm(m) in norm(c["text"]) for m in markers):
            out.add(c["alias"])
    for f in store["facts"].values():
        body = " ".join(
            store["chunks"][k]["text"] for k in f["evidence"] if k in store["chunks"]
        )
        if any(norm(m) in norm(body) for m in markers):
            out.add(f["alias"])
    return out


def cited_closure(store: dict, cited: list[str]) -> set[str]:
    """인용한 별칭 + 그 사실이 딸고 있는 근거 청크까지. 사실을 인용하면 원문도 본 것이다."""
    by_alias = {f["alias"]: f for f in store["facts"].values()}
    out = set(cited)
    for a in cited:
        f = by_alias.get(a)
        if f:
            out |= {store["chunks"][k]["alias"] for k in f["evidence"] if k in store["chunks"]}
    return out


def stage_judge_score(run_tag: str, drafts: list[str], jtag: str, tau: int = 7) -> str:
    """판정 결과를 GT·hard_negative·라벨없음으로 갈라 채점한다. LLM 호출 없음."""
    markers_all = json.loads(MARKERS_PATH.read_text(encoding="utf-8"))
    rows, gt_rows, hn_rows, excl_rows = [], [], [], []
    curve = {t: {"tp": 0, "grounded": 0, "hn": 0, "noise": 0, "alarm": 0} for t in range(11)}
    tot = {"pos": 0, "reachable": 0, "hn": 0, "unl": 0}
    hygiene = {"unknown_alias": 0, "empty_cited_high": 0, "off_ref": 0}
    used = [usage.empty()]

    for draft in drafts:
        gt = json.loads((DATA_DIR / f"{DRAFTS[draft]}.gt.json").read_text(encoding="utf-8"))
        nd = norm((DATA_DIR / f"{DRAFTS[draft]}.txt").read_text(encoding="utf-8"))
        claims = json.loads(
            (OUT_DIR / f"claims_{run_tag}_{draft}.json").read_text(encoding="utf-8")
        )["claims"]
        evidence = json.loads(
            (OUT_DIR / f"evidence_{run_tag}_{draft}.json").read_text(encoding="utf-8")
        )
        store = build_docstore(evidence)
        jpath = OUT_DIR / f"judge_{run_tag}_{jtag}_{draft}.json"
        jd = json.loads(jpath.read_text(encoding="utf-8"))
        used.append(jd["usage"])
        by = {v["claim_index"]: v for v in jd["verdicts"]}
        all_alias = {n["alias"] for kind in ("chunks", "facts", "entities")
                     for n in store[kind].values()}
        refs_by_idx = {r["claim_index"]: r for r in store["refs"]}

        pos_idx: set[int] = set()
        for i, err in enumerate(gt["errors"], 1):
            gid = f"{draft}-GT{i}"
            idxs = match_claim_indices(err["quote"], claims, nd)
            pos_idx |= set(idxs)
            spec = markers_all.get(gid, {})
            unreachable = bool(spec.get("unreachable"))
            mb = marker_bearing_aliases(store, spec.get("markers", []))
            scored = [(j, by[j]["score"]) for j in idxs if j in by]
            best = max((s for _, s in scored), default=None)
            best_j = max(scored, key=lambda x: x[1])[0] if scored else None
            cited = by[best_j]["cited"] if best_j is not None else []
            # 접지 = 고득점이면서 실제로 마커를 담은 노드를 인용했는가. max 집계의 낙관 편향
            # (엉뚱한 형제 claim이 우연히 높아서 맞힌 것처럼 보이는 것)을 걸러낸다.
            grounded = bool(mb and (cited_closure(store, cited) & mb))
            tot["pos"] += 1
            if not unreachable:
                tot["reachable"] += 1
            for t in range(11):
                if best is not None and best >= t:
                    curve[t]["tp"] += 1
                    if grounded and not unreachable:
                        curve[t]["grounded"] += 1
            gt_rows.append({
                "gid": gid, "category": err.get("category", ""), "n": len(idxs),
                "scores": [s for _, s in scored], "best": best,
                "spread": (max(s for _, s in scored) - min(s for _, s in scored)) if scored else 0,
                "grounded": grounded, "unreachable": unreachable, "cited": cited,
            })

        hn_idx: set[int] = set()
        for n in gt.get("hard_negatives", []):
            idxs = [j for j in match_claim_indices(n["quote"], claims, nd) if j not in pos_idx]
            hn_idx |= set(idxs)
            scored = [by[j]["score"] for j in idxs if j in by]
            best = max(scored, default=None)
            if idxs:
                tot["hn"] += 1
                for t in range(11):
                    if best is not None and best >= t:
                        curve[t]["hn"] += 1
            hn_rows.append({"draft": draft, "quote": n["quote"], "extracted": bool(idxs),
                            "best": best, "reason": n.get("reason", "")})

        excl_idx: set[int] = set()
        for n in gt.get("excluded", []):
            idxs = [j for j in match_claim_indices(n["quote"], claims, nd) if j not in pos_idx]
            excl_idx |= set(idxs)
            scored = [by[j]["score"] for j in idxs if j in by]
            if idxs:
                excl_rows.append({"draft": draft, "quote": n["quote"],
                                  "best": max(scored, default=None)})

        unl = [j for j in range(len(claims)) if j not in pos_idx | hn_idx | excl_idx]
        tot["unl"] += len(unl)
        for j in unl:
            v = by.get(j)
            if v:
                for t in range(11):
                    if v["score"] >= t:
                        curve[t]["noise"] += 1
        for j, v in by.items():
            if j in excl_idx:
                continue
            for t in range(11):
                if v["score"] >= t:
                    curve[t]["alarm"] += 1
            bad = [a for a in v["cited"] if a not in all_alias]
            hygiene["unknown_alias"] += len(bad)
            if v["score"] >= tau and not v["cited"]:
                hygiene["empty_cited_high"] += 1
            ref = refs_by_idx.get(j, {})
            own = {store[k][x]["alias"] for k in ("chunks", "facts", "entities")
                   for x in ref.get(k, []) if x in store[k]}
            hygiene["off_ref"] += len([a for a in v["cited"] if a in all_alias and a not in own])

        det = sum(1 for r in gt_rows if r["gid"].startswith(draft) and (r["best"] or 0) >= tau)
        gsum = [r for r in gt_rows if r["gid"].startswith(draft)]
        rows.append(
            f"| {draft} | {det}/{len(gsum)} | "
            f"{sum(1 for r in gsum if r['grounded'] and (r['best'] or 0) >= tau)}/{len(gsum)} | "
            f"{sum(r['best'] or 0 for r in gsum) / max(len(gsum), 1):.1f} | "
            f"{len(unl)} | {sum(1 for j in unl if (by.get(j) or {}).get('score', 0) >= tau)} |"
        )

    n = max(len(drafts), 1)
    u = usage.merge(used)
    lines = [
        f"# judge 판정 평가 — {run_tag} / {jtag} (운영점 τ={tau})", "",
        "## 초고별 요약", "",
        "| 초고 | GT 검출 | 접지 검출 | GT 평균점수 | 라벨없음 | τ 이상 |",
        "|---|---|---|---|---|---|", *rows, "",
        f"판정 토큰: prompt {u['prompt_tokens']:,} / completion {u['completion_tokens']:,} "
        f"(└reasoning {u['reasoning_tokens']:,}) — 편당 비용 ${cost_usd(u) / n:.4f}", "",
        "## 임계값 곡선", "",
        f"| τ | GT 검출 /{tot['pos']} | 접지 /{tot['reachable']} | "
        f"hard-neg 오탐 /{tot['hn']} | 소음률 상한 /{tot['unl']} | 편당 알림 |",
        "|---|---|---|---|---|---|",
    ]
    for t in range(1, 11):
        c = curve[t]
        lines.append(
            f"| {t} | {c['tp']} | {c['grounded']} | {c['hn']} | "
            f"{c['noise']} ({c['noise'] / max(tot['unl'], 1) * 100:.1f}%) | {c['alarm'] / n:.1f} |"
        )
    lines += [
        "", "## GT 상세", "",
        "| GT | 카테고리 | claim 수 | 점수 | max | spread | 접지 | 인용 |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in gt_rows:
        # 접지는 "검출됐고 + 실제 마커 노드를 인용했다"일 때만 O다. 점수가 낮으면 인용이
        # 맞아도 검출이 아니므로, 그 경우는 "근거를 받고도 못 맞힘"(판정 실패)으로 적는다.
        detected = (r["best"] or 0) >= tau
        if r["unreachable"]:
            mark = "(도달불가)"
        elif detected:
            mark = "O" if r["grounded"] else "X(무접지)"
        else:
            mark = "미검출·근거있음" if r["grounded"] else "미검출·근거없음"
        lines.append(
            f"| {r['gid']} | {r['category']} | {r['n']} | {r['scores']} | "
            f"{r['best']} | {r['spread']} | {mark} | {' '.join(r['cited'][:4]) or '-'} |"
        )
    lines += ["", "## hard-negative (오탐 회귀 테스트)", "",
              "| 초고 | 서술 | 추출됨 | 점수 | GT가 밝힌 이유 |", "|---|---|---|---|---|"]
    for r in hn_rows:
        lines.append(f"| {r['draft']} | {r['quote'][:28]} | {'O' if r['extracted'] else 'X(judge 무관)'} | "
                     f"{r['best'] if r['best'] is not None else '-'} | {r['reason'][:52]} |")
    if excl_rows:
        lines += ["", "excluded(채점 제외) 관찰: " + ", ".join(
            f"{r['draft']} {r['best']}점" for r in excl_rows)]
    lines += [
        "", "## cited 위생", "",
        f"- 문서고에 없는 별칭 인용: **{hygiene['unknown_alias']}건**",
        f"- 인용 없이 τ 이상 점수: **{hygiene['empty_cited_high']}건**",
        f"- 자기 참조 밖 노드 인용: {hygiene['off_ref']}건 "
        "(결함이 아니라, 검색 라우팅이 놓친 근거를 문서고 공유가 주웠다는 신호)",
        "", "## 읽는 법", "",
        f"- **소음률은 FP율이 아니라 상한**이다. 라벨 없는 {tot['unl']}개는 정답이 없고, "
        "6화 고유 사건은 근거가 없어 낮은 점수가 정상이다(errors.md).",
        f"- hard-negative는 표본이 {tot['hn']}건뿐이라 비율이 아니라 회귀 테스트로 읽어야 한다.",
        "- 접지 검출은 '고득점이면서 실제 마커 노드를 인용한' 건수다. "
        "검출과 접지의 차이가 운으로 맞힌 양이다.",
        "",
    ]
    report = "\n".join(lines)
    (OUT_DIR / f"report_judge_{run_tag}_{jtag}.md").write_text(report, encoding="utf-8")
    return report


