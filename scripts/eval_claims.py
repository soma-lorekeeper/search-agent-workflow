JUDGE_CACHE_KEY = "gyeol-eval-claims-judge"  # 추출·검증과 프롬프트 모양이 달라 키를 분리한다
JUDGE_CACHE_DIR = CACHE_DIR / "judge"
JUDGE_PROMPT_VERSION = "p2"  # 기본은 baseline 유지. --judge-prompt로 바꾼다
#   p1 → p2: 사실의 `순서`로 선후를 따지는 원칙 6 + 예시 8 추가. p1에서 v1-GT3(죽었다는
#   인물이 뒤 사건에 등장)과 v5-GT1(이동 방향)을 "근거 없음"으로 흘려보냈다.
#   p2 → p3: 판정 절차 3단계 + 원칙 1·2·4·6 정밀화 + 원칙 7 신설 + 예시 9~15. p2가
#   놓친 5건이 전부 "확인되지 않는다"류의 대조 생략이었다(아래 _JUDGE_CRITERIA_P3 주석).


def judge_tag(batch_size: int | None, n: int = 1, effort: str | None = None) -> str:
    """판정 아티팩트 식별자. run_tag가 "무엇을 판정했나"라면 이건 "어떻게 판정했나"다."""
    parts = [JUDGE_PROMPT_VERSION]
    if batch_size:
        parts.append(f"b{batch_size}")
    if n > 1:
        parts.append(f"n{n}")
    if effort:
        parts.append(effort)
    return "-".join(parts)


def build_judge_system(store: dict, draft_text: str | None = None) -> str:
    """판정용 system 프롬프트. 정적(기준+예시)을 앞, 초고별 문서고를 뒤에 둔다.

    배치를 나눠도 이 문자열이 안 바뀌므로 프롬프트 캐시의 안정 prefix가 된다 — 배치별로
    참조 노드만 잘라 넣으면 캐시가 깨질 뿐 아니라 "모델이 본 정보량"이 배치마다 달라져
    단일 vs 배치 비교가 두 변수를 동시에 건드리게 된다.
    """
    criteria, fewshot = _JUDGE_PROMPTS[JUDGE_PROMPT_VERSION]
    parts = [criteria, fewshot, "[문서고]\n" + render_docstore(store)]
    # 원고는 문서고 **뒤**에 둔다. 앞에 두면 근거보다 검증 대상을 먼저 읽게 되고,
    # 첫 주입 실험에서 무너진 자리가 정확히 "문서고 대신 원고를 근거로 삼는" 것이었다.
    if draft_text:
        parts.append("[신규 회차 원고]\n" + draft_text)
    return "\n\n".join(parts)


def _judge_cache_path(system: str, user: str, n: int, effort: str | None) -> Path:
    key = hashlib.sha1(
        "|".join([EXTRACT_MODEL, JUDGE_PROMPT_VERSION, system, user,
                  f"n{n}", effort or "-"]).encode("utf-8")
    ).hexdigest()
    return JUDGE_CACHE_DIR / f"{key}.json"


async def _judge_once(
    system: str, user: str, n: int, refresh: bool, effort: str | None = None
) -> dict:
    """판정 LLM 호출 1회. 응답 원문을 함께 저장해 파싱 규칙이 바뀌어도 재호출이 없게 한다.

    n>1이면 같은 요청에서 표본을 n개 받는다(자기일관성 측정용). 입력이 한 번만 과금되는 것도
    이득이지만, 더 중요한 건 **완전히 같은 조건에서 뽑은 표본**이라는 점이다 — 별도 호출로
    반복하면 시간차와 프롬프트 캐시 적중 여부가 회차마다 달라져, "같은 입력에 얼마나 다른
    답을 내는가"라는 질문 자체가 오염된다.
    """
    cached_at = _judge_cache_path(system, user, n, effort)
    if cached_at.exists() and not refresh:
        return json.loads(cached_at.read_text(encoding="utf-8"))

    kwargs = {
        "model": EXTRACT_MODEL,
        "response_format": {"type": "json_object"},
        "prompt_cache_key": JUDGE_CACHE_KEY,
        "messages": [
            {"role": "system", "content": system},
            {"role": "user", "content": user},
        ],
    }
    if n > 1:
        kwargs["n"] = n
    # 지정하지 않으면 파라미터 자체를 빼서 API 기본값을 쓴다(pipeline.py:102-105와 같은 방식).
    # 추출에서는 미지정이 최선이었고, 판정도 같은 조건으로 기준선을 잡은 뒤 승격을 A/B로 잰다.
    if effort:
        kwargs["reasoning_effort"] = effort
    response = await _create_with_retry(**kwargs)
    payload = {
        "raw": response.choices[0].message.content or "{}",
        "raws": [c.message.content or "{}" for c in response.choices],
        "finish_reason": response.choices[0].finish_reason,
        "usage": usage.from_response(response),
    }
    JUDGE_CACHE_DIR.mkdir(parents=True, exist_ok=True)
    cached_at.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    return payload


async def _create_with_retry(**kwargs):
    """RateLimitError에 지수 백오프 + 지터. src/contradiction/agent.py:33-53과 같은 패턴.

    그쪽을 import하지 않는 이유는 private 함수인 데다 그 모듈이 tools/prompts를 끌고 오기
    때문이다. 판정은 한 호출에 27k를 쓰므로 몇 편만 겹쳐도 조직 TPM에 순간적으로 몰린다.
    """
    for attempt in range(5):
        try:
            return await _client.chat.completions.create(**kwargs)
        except RateLimitError:
            if attempt == 4:
                raise
            await asyncio.sleep(min(2**attempt, 30) + random.uniform(0, 1))


_VERDICT_ID = re.compile(r"^P(\d+)$")


def _parse_verdicts(
    raw: str, wanted: list[int], claims: list[dict] | None = None
) -> tuple[dict[int, dict], list[str]]:
    """판정 JSON을 claim 인덱스 → 판정 dict로 푼다. 위반은 버리지 않고 flag로 남긴다.

    agent.py:65-81이 라벨 값을 검증하지 않아 오타 라벨이 조용히 소실되던 것의 반면교사다.
    누락된 claim을 0점으로 채우지 않는 게 중요하다 — 0은 "근거가 없어 낮은 점수"라는 유효한
    판정값이라, 누락을 0으로 메우면 둘을 영영 구분할 수 없다.

    두 형식을 받는다. p2~p4는 `{"i": 12}`, p5는 `{"claimId": "P12", "lineIds": [6]}`이다.
    claims를 주면 lineIds를 그 claim의 lines와 대조해 어긋나면 lines 전체로 되돌린다.
    """
    problems: list[str] = []
    try:
        data = json.loads(raw)
    except json.JSONDecodeError:
        return {}, ["json_parse_failed"]

    out: dict[int, dict] = {}
    for v in data.get("verdicts") or []:
        flags = []
        cid = v.get("claimId")
        m = _VERDICT_ID.match(cid) if isinstance(cid, str) else None
        if m is not None:
            idx = int(m.group(1)) - 1  # P12 → 인덱스 11
        else:
            try:
                idx = int(v.get("i")) - 1  # 프롬프트는 1-base, 내부는 0-base
            except (TypeError, ValueError):
                problems.append("bad_index")
                continue
            if cid is not None:
                flags.append("claim_id_unknown")
        raw_score = v.get("score")
        try:
            score = int(raw_score)
        except (TypeError, ValueError):
            score, flags = 0, flags + ["score_not_int"]
        if score < 0 or score > 10:
            flags.append("score_out_of_range")
            score = max(0, min(10, score))
        cited = [str(c) for c in (v.get("cited") or [])]

        # lineIds는 그 claim이 제시한 후보 줄의 부분집합이어야 한다. 아니면 후보 전체로
        # 되돌린다 — 판정기는 원고를 못 보므로 없는 번호를 지어낼 여지가 있다.
        claim = claims[idx] if claims and 0 <= idx < len(claims) else None
        cand = list((claim or {}).get("lines") or [])
        picked = [n for n in (v.get("lineIds") or []) if isinstance(n, int)]
        if cand and (not picked or not set(picked) <= set(cand)):
            flags.append("line_fallback")
            picked = cand

        out[idx] = {"claim_index": idx, "score": score, "raw_score": raw_score,
                    "claim_id": (claim or {}).get("id"), "line_ids": picked,
                    "cited": cited, "reason": str(v.get("reason") or ""), "flags": flags}

    missing = [i for i in wanted if i not in out]
    if missing:
        problems.append(f"missing:{len(missing)}")
    extra = [i for i in out if i not in set(wanted)]
    if extra:
        problems.append(f"extra:{len(extra)}")
    return out, problems


async def stage_judge(
    run_tag: str,
    draft: str,
    batch_size: int | None = None,
    n: int = 1,
    refresh: bool = False,
    effort: str | None = None,
) -> dict:
    """문서고를 근거로 claim 전체를 0~10점으로 판정한다.

    n>1이면 표본을 n개 받아 claim별 점수 분포를 함께 기록한다. 대표값은 **중앙값**을 쓴다 —
    표본이 흔들리는 claim에서 최댓값을 쓰면 "가장 운이 좋았던 판정"만 남아 오탐 쪽으로
    치우친다(GT 집계에서 형제 claim에 max를 쓰는 것과는 목적이 다르다. 거긴 서로 다른
    서술 중 무엇이라도 잡혔나를 보는 것이고, 여긴 같은 서술의 판정이 얼마나 안정적인가다).
    """
    claims = json.loads(
        (OUT_DIR / f"claims_{run_tag}_{draft}.json").read_text(encoding="utf-8")
    )["claims"]
    evidence = json.loads(
        (OUT_DIR / f"evidence_{run_tag}_{draft}.json").read_text(encoding="utf-8")
    )
    store = build_docstore(evidence)
    # 원고 전문 주입은 한 번 실패해 되돌린 자리다. v5의 "원고 안에서만 성립하는 모순"을 노린
    # 변경이었는데, judge가 원고를 읽고 cited에 `원고`까지 찍으면서도 그 3건을 하나도 못
    # 살렸고 오히려 v4가 5/5 → 2/5로 무너졌다(검출 21 → 16, 소음 0.3% → 1.6%). 입력이 31k로
    # 커지면서 문서고 대조 쪽 주의가 옅어진 것으로 봤다.
    # p6은 그때와 두 가지가 다르다 — 원고에 라인 번호가 붙고, "원고는 근거가 아니다"라는
    # 제한 문단이 프롬프트에 들어간다. 그 제한이 먹히는지를 재는 것이 p6의 목적이다.
    draft_text = None
    if JUDGE_PROMPT_VERSION in _JUDGE_NEEDS_DRAFT:
        raw_text = (DATA_DIR / f"{DRAFTS[draft]}.txt").read_text(encoding="utf-8")
        draft_text = number_lines(split_lines(raw_text))
    system = build_judge_system(store, draft_text)

    idxs = list(range(len(claims)))
    batches = (
        [idxs] if not batch_size
        else [idxs[i : i + batch_size] for i in range(0, len(idxs), batch_size)]
    )

    verdicts: dict[int, dict] = {}
    problems: list[str] = []
    finish_reasons: list[str] = []
    used = [usage.empty()]
    for bi, batch in enumerate(batches):
        user = render_claim_refs(store, claims, batch, include_context=True)
        payload = await _judge_once(system, user, n, refresh, effort)
        samples: list[dict[int, dict]] = []
        for si, raw in enumerate(payload.get("raws") or [payload["raw"]]):
            parsed, probs = _parse_verdicts(raw, batch, claims)
            samples.append(parsed)
            problems += [f"b{bi}s{si}:{p}" for p in probs]
        for idx in {i for s in samples for i in s}:
            got = [s[idx] for s in samples if idx in s]
            scores = sorted(v["score"] for v in got)
            rep = got[len(got) // 2] if len(got) > 1 else got[0]
            verdicts[idx] = {
                **rep,
                "score": scores[len(scores) // 2],  # 중앙값 — 운 좋은 한 표본에 끌리지 않게
                "samples": scores if len(scores) > 1 else None,
            }
        finish_reasons.append(payload["finish_reason"])
        used.append(payload["usage"])

    missing = [i for i in idxs if i not in verdicts]
    out = {
        "run": run_tag, "draft": draft, "jtag": judge_tag(batch_size, n, effort),
        "prompt_version": JUDGE_PROMPT_VERSION, "batch_size": batch_size or 0,
        "n": n, "effort": effort or "(미지정)", "model": EXTRACT_MODEL,
        # 문서고 별칭은 자연키 정렬이라 retrieve를 다시 돌려 노드 집합이 바뀌면 번호가 밀린다.
        # 지문을 남겨 두면 재채점 때 옛 cited가 엉뚱한 노드를 가리키는 걸 잡을 수 있다.
        "store_fingerprint": f"C{len(store['chunks'])}/F{len(store['facts'])}/E{len(store['entities'])}",
        "verdicts": [
            {**verdicts[i], "quote": claims[i].get("quote", "")}
            for i in sorted(verdicts)
        ],
        "missing_indices": missing,
        "problems": problems,
        "finish_reasons": finish_reasons,
        "usage": usage.merge(used),
    }
    path = OUT_DIR / f"judge_{run_tag}_{judge_tag(batch_size, n, effort)}_{draft}.json"
    path.write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")
    u = out["usage"]
    print(f"  [judge] {draft}: claim {len(claims)}개 → 판정 {len(verdicts)}개 "
          f"(배치 {len(batches)}회, 누락 {len(missing)}, "
          f"prompt {u['prompt_tokens']:,} / completion {u['completion_tokens']:,})"
          + (f" 문제: {problems}" if problems else ""))
    return out


