# 기본 조합에까지 접미사를 붙이면 기존 아티팩트 이름이 깨진다. 그래서 기본과 다를 때만 붙인다.
DEFAULT_ROUTE = {"sav": "type", "lean": "slim", "stm": "broadcast",
                 "qav": "qav", "qav2": "qav", "qav3": "qav", "qav4": "qav"}


def tag(
    variant: str,
    effort: str | None,
    schema: str = "sav",
    route_mode: str | None = None,
    include_graph: bool = False,
    sample: int = 0,
) -> str:
    """아티팩트 파일명에 쓰는 실행 식별자. effort·schema·route를 붙여 실험 실행이 기본
    실행을 덮어쓰지 않게 한다(나란히 비교해야 효과를 잴 수 있다).

    sample은 같은 구성을 여러 번 뽑을 때의 회차다(0은 접미사 없음 — 기존 아티팩트와
    이름이 그대로 유지된다). 추출은 실행마다 결과가 흔들리므로(quote 자카드 14%) 구성
    비교는 n=1로는 성립하지 않는다.

    `-legacy` 접미사가 붙은 아티팩트는 검색 결과에 `[관련 그래프]` 부록이 딸려오던 시절의
    것이다. 그중 `whole-bc-trim-legacy`(부록을 텍스트에서 떼어낸 것)가 지금의 `whole-bc`와
    같은 조건이고, `whole-bc-legacy`는 부록을 포함한 수치다(근거 토큰 855k vs 283k).
    """
    parts = [variant]
    if effort:
        parts.append(effort)
    if schema != "sav":
        parts.append(schema)
    if route_mode and route_mode != DEFAULT_ROUTE[schema]:
        parts.append({"broadcast": "bc", "slim": "slim", "type": "type",
                      "qav": "qav", "qav-q": "qavq"}[route_mode])
    if include_graph:
        parts.append("g")
    if sample:
        parts.append(f"s{sample}")
    return "-".join(parts)

