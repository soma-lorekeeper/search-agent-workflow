async def main() -> int:
    global JUDGE_PROMPT_VERSION
    parser = argparse.ArgumentParser(description="claim 추출 → 검색 도달 평가")
    parser.add_argument(
        "--stage", default="all",
        choices=["extract", "retrieve", "score", "assemble", "judge", "judge-score",
                 "all", "compare"]
    )
    # 확정 구성: line-3000 + qav2. 원고를 L1~LN으로 번호 붙인 뒤 3000자 단위(편당 2조각)로
