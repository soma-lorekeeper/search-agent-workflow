# 비용 환산 단가(1M 토큰당 USD). 실제 청구 단가와 다르면 여기만 고치고 --stage score를
# 다시 돌리면 된다 — 재채점은 LLM을 부르지 않으므로 공짜다.
PRICE_IN = 0.20
PRICE_CACHED = 0.02
PRICE_OUT = 1.20


def cost_usd(u: dict[str, int]) -> float:
    """usage 한 덩어리의 비용. cached_tokens는 prompt_tokens에 포함된 값이라 빼고 센다."""
    fresh = u["prompt_tokens"] - u["cached_tokens"]
    return (
        fresh * PRICE_IN + u["cached_tokens"] * PRICE_CACHED + u["completion_tokens"] * PRICE_OUT
    ) / 1_000_000


def cold_cost_usd(u: dict[str, int]) -> float:
    """캐시가 하나도 안 걸렸다고 가정한 비용. 실행 순서에 따라 캐시 적중률이 달라지므로
    구성끼리 비교할 때는 이 값을 써야 한다."""
    return (u["prompt_tokens"] * PRICE_IN + u["completion_tokens"] * PRICE_OUT) / 1_000_000


