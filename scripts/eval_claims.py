def render_comparison(drafts: list[str]) -> str:
    """아티팩트가 남아 있는 모든 실행을 한 표로 비교한다.

    비용은 캐시 미적용 값으로 비교한다 — 실측 캐시 적중률은 실행 순서에 좌우돼서,
    나중에 돌린 구성일수록 싸 보이는 착시가 생긴다.
    """
    runs = sorted({p.name.split("_")[1] for p in OUT_DIR.glob("claims_*_v*.json")})
    rows = []
    for run in runs:
        if not all((OUT_DIR / f"evidence_{run}_{d}.json").exists() for d in drafts):
            continue
        scored = stage_score(run, drafts)
        tot_ex = tot_gt = tot_reach = tot_den = n_claims = 0
        tot = usage.empty()
        for d in scored["per_draft"].values():
            tot_ex += sum(1 for r in d["rows"] if r["extracted"])
            tot_gt += len(d["rows"])
            den = [r for r in d["rows"] if not r["unreachable"]]
            tot_reach += sum(1 for r in den if r["reached"])
            tot_den += len(den)
            n_claims += d["n_claims"]
            tot = usage.merge([tot, d["usage"]])
        n = max(len(drafts), 1)
        rows.append(
            {
                "run": run,
                "cov": (tot_ex, tot_gt),
                "reach": (tot_reach, tot_den),
                "claims": n_claims,
                "calls": tot["calls"] // n,
                "in_tok": tot["prompt_tokens"] // n,
                "out_tok": tot["completion_tokens"] // n,
                "reasoning": tot["reasoning_tokens"] // n,
                "cold": cold_cost_usd(tot) / n,
            }
        )

    rows.sort(key=lambda r: (-r["cov"][0], -r["reach"][0], r["cold"]))
    lines = [
        "# 구성 비교 — claim 추출·검색 도달",
        "",
        "| 구성 | ①커버리지 | ②도달률 | claim 수 | 회차당 호출 | 회차당 입력 tok | "
        "회차당 출력 tok | └reasoning | 회차당 비용 |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['run']} | {r['cov'][0]}/{r['cov'][1]} | {r['reach'][0]}/{r['reach'][1]} | "
            f"{r['claims']} | {r['calls']} | {r['in_tok']:,} | {r['out_tok']:,} | "
            f"{r['reasoning']:,} | ${r['cold']:.4f} |"
        )
    lines += [
        "",
        "커버리지 내림차순 → 도달률 내림차순 → 비용 오름차순으로 정렬했다. "
        "비용은 캐시 미적용 기준(구성 간 공정 비교).",
        "",
    ]
    return "\n".join(lines)


