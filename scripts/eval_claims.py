def _count_tokens(text: str) -> int:
    """tiktoken이 있으면 실측, 없으면 근사치. 근사여도 구성 간 비교는 성립한다."""
    try:
        import tiktoken

        return len(tiktoken.get_encoding("o200k_base").encode(text))
    except Exception:  # noqa: BLE001 — 미설치·인코딩 다운로드 실패 모두 근사로 폴백
        return len(text) // 2


def stage_assemble(run_tag: str, drafts: list[str]) -> str:
    """evidence를 노드 병합 문서고로 조립하고, 토큰과 도달률 재현을 함께 잰다."""
    scored_ch = stage_score(run_tag, drafts, pool_source="channels")
    scored_ds = stage_score(run_tag, drafts, pool_source="docstore")

    rows, tot = [], {"ch": 0, "doc": 0, "ref": 0}
    mismatches: list[str] = []
    for draft in drafts:
        evidence = json.loads(
            (OUT_DIR / f"evidence_{run_tag}_{draft}.json").read_text(encoding="utf-8")
        )
        claims = json.loads(
            (OUT_DIR / f"claims_{run_tag}_{draft}.json").read_text(encoding="utf-8")
        )["claims"]
        store = build_docstore(evidence)
        doc_text, ref_text = render_docstore(store), render_claim_refs(store, claims)

        ch_tok = _count_tokens(
            "\n".join(ch["content"] for r in evidence["records"] for ch in r["channels"])
        )
        doc_tok, ref_tok = _count_tokens(doc_text), _count_tokens(ref_text)
        tot["ch"] += ch_tok; tot["doc"] += doc_tok; tot["ref"] += ref_tok

        (OUT_DIR / f"context_{run_tag}_{draft}.json").write_text(
            json.dumps(store, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        (OUT_DIR / f"context_{run_tag}_{draft}.txt").write_text(
            doc_text + "\n\n" + ref_text, encoding="utf-8"
        )

        # GT별 O/X가 두 경로에서 같은지 — 합계만 보면 상쇄된 차이를 놓친다.
        for a, b in zip(scored_ch["per_draft"][draft]["rows"],
                        scored_ds["per_draft"][draft]["rows"]):
            if a["reached"] != b["reached"]:
                mismatches.append(f"{a['gid']}(채널={a['reached']} 문서고={b['reached']})")

        rows.append(
            f"| {draft} | {ch_tok:,} | {doc_tok:,} | {ref_tok:,} | {doc_tok + ref_tok:,} | "
            f"{(doc_tok + ref_tok) / max(ch_tok, 1) * 100:.0f}% | "
            f"{len(store['chunks'])}/{len(store['facts'])}/{len(store['entities'])} |"
        )
        print(f"  [assemble] {draft}: 청크 {len(store['chunks'])} / 사실 {len(store['facts'])}"
              f" / 개체 {len(store['entities'])} → {doc_tok + ref_tok:,} tok "
              f"(채널 {ch_tok:,} 대비 {(doc_tok + ref_tok) / max(ch_tok, 1) * 100:.0f}%)")

    def totals(scored):
        ex = sum(1 for d in scored["per_draft"].values() for r in d["rows"] if r["extracted"])
        den = [r for d in scored["per_draft"].values() for r in d["rows"] if not r["unreachable"]]
        return ex, sum(1 for r in den if r["reached"]), len(den)

    ex, reach_ch, den = totals(scored_ch)
    _, reach_ds, _ = totals(scored_ds)
    n = max(len(drafts), 1)

    lines = [
        f"# judge 컨텍스트 조립 — {run_tag}", "",
        "| 초고 | 채널 tok | 문서고 tok | 참조목록 tok | 합계 tok | 채널대비 | 청크/사실/개체 |",
        "|---|---|---|---|---|---|---|",
        *rows,
        f"| **합계** | **{tot['ch']:,}** | **{tot['doc']:,}** | **{tot['ref']:,}** | "
        f"**{tot['doc'] + tot['ref']:,}** | "
        f"**{(tot['doc'] + tot['ref']) / max(tot['ch'], 1) * 100:.0f}%** | |",
        "",
        f"**초고 1편당 judge 입력: {(tot['doc'] + tot['ref']) // n:,} tok** "
        f"(채널 그대로면 {tot['ch'] // n:,} tok)", "",
        f"커버리지 {ex}/25 · 도달률 채널 {reach_ch}/{den} · 문서고 {reach_ds}/{den}", "",
        ("**GT별 도달 판정이 두 경로에서 완전히 일치한다** — 문서고가 근거를 잃지 않았다는 뜻이다."
         if not mismatches else
         "**불일치: " + ", ".join(mismatches) + "** — 문서고 조립에서 근거가 샜다."),
        "",
        "문서고는 노드(청크·사실·개체)를 한 번만 싣고 claim은 별칭으로 가리킨다. 채널 텍스트가 "
        "claim마다 같은 청크를 반복해 싣던 것과 달리, 같은 근거를 여러 claim이 공유해도 분량이 "
        "늘지 않는다.",
        "",
    ]
    report = "\n".join(lines)
    (OUT_DIR / f"report_context_{run_tag}.md").write_text(report, encoding="utf-8")
    return report


